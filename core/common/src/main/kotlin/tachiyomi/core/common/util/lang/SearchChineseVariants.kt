    /**
     * The simplified form of [char], or [char] itself when it is not a traditional character
     * we know about.
     */
    fun toSimplified(char: Char): Char {
        var low = 0
        var high = TRADITIONAL_CHARS.length - 1
        while (low <= high) {
            val mid = (low + high) ushr 1
            val candidate = TRADITIONAL_CHARS[mid]
            when {
                candidate < char -> low = mid + 1
                candidate > char -> high = mid - 1
                else -> return SIMPLIFIED_CHARS[mid]
            }
        }
        return char
    }
